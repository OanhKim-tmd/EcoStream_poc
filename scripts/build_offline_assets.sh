#!/usr/bin/env bash
# Build the offline UI assets in ecostream/app/static/vendor/:
#   app.css            Tailwind CSS v3 build (replaces the Play CDN) with fonts inlined
#   fonts/*.woff2      Inter + JetBrains Mono (latin + vietnamese subsets)
# Needs Internet once (npm). Run from the project root:
#   bash scripts/build_offline_assets.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/ecostream/app/static/vendor"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "[1/3] Installing Tailwind 3.4.17 and fonts into $WORK ..."
(cd "$WORK" && npm init -y >/dev/null && npm install --no-audit --no-fund --silent \
  tailwindcss@3.4.17 @fontsource/inter@5.1.1 @fontsource/jetbrains-mono@5.1.1)

echo "[2/3] Copying fonts and writing fonts.css ..."
mkdir -p "$VENDOR/fonts"
python3 - "$WORK/node_modules" "$VENDOR" <<'PY'
import re, shutil, sys
from pathlib import Path
nm, vendor = Path(sys.argv[1]), Path(sys.argv[2])
faces = {"inter": [400, 500, 600, 700], "jetbrains-mono": [400, 500, 600]}
out = ["/* Generated by scripts/build_offline_assets.sh from @fontsource (SIL OFL 1.1). */"]
for family, weights in faces.items():
    pkg = nm / "@fontsource" / family
    for subset in ("vietnamese", "latin"):
        for w in weights:
            css = (pkg / f"{subset}-{w}.css").read_text(encoding="utf-8")
            css = re.sub(r",\s*url\([^)]*\.woff\)\s*format\(['\"]woff['\"]\)", "", css)
            for name in re.findall(r"url\(\./files/([^)]+\.woff2)\)", css):
                shutil.copy2(pkg / "files" / name, vendor / "fonts" / name)
            out.append(css.replace("url(./files/", "url(./fonts/").strip())
(vendor / "fonts.css").write_text("\n".join(out) + "\n", encoding="utf-8")
print("  fonts:", len(list((vendor / "fonts").glob("*.woff2"))), "files")
PY

echo "[3/3] Building app.css ..."
(cd "$ROOT" && "$WORK/node_modules/.bin/tailwindcss" \
  -c ecostream/app/static/vendor/tailwind.config.js \
  -i ecostream/app/static/vendor/input.css \
  -o ecostream/app/static/vendor/app.css --minify)

grep -q "font-face" "$VENDOR/app.css" || { echo "ERROR: fonts not inlined into app.css"; exit 1; }
echo "Done: $(du -h "$VENDOR/app.css" | cut -f1) app.css"
